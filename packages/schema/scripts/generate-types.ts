/**
 * Generates src/generated/*.ts from schemas/*.schema.json.
 * Run `pnpm --filter @gitleaf/schema generate`. CI fails if the output drifts.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { compile } from 'json-schema-to-typescript';

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

function stripPatternProperties(node: unknown): void {
  if (Array.isArray(node)) {
    node.forEach(stripPatternProperties);
  } else if (isRecord(node)) {
    const obj = node;
    if (obj.patternProperties && typeof obj.patternProperties === 'object') {
      const keys = Object.keys(obj.patternProperties);
      if (keys.every((k) => k === '^x-')) delete obj.patternProperties;
    }
    Object.values(obj).forEach(stripPatternProperties);
  }
}

const root = new URL('..', import.meta.url).pathname;
const schemasDir = join(root, 'schemas');
const outDir = join(root, 'src', 'generated');
mkdirSync(outDir, { recursive: true });

const names: string[] = [];
for (const file of readdirSync(schemasDir).sort()) {
  if (!file.endsWith('.schema.json')) continue;
  const schema = JSON.parse(readFileSync(join(schemasDir, file), 'utf8')) as Record<
    string,
    unknown
  >;
  const base = file.replace(/\.schema\.json$/, '');
  const typeName = base
    .split('-')
    .map((part) => (/^\d+$/.test(part) ? `V${part}` : part.charAt(0).toUpperCase() + part.slice(1)))
    .join('');
  // The generator names the root type after `title`; we want the stable name.
  schema.title = typeName;
  // `^x-` extension keys would become a loose index signature. They are typed
  // separately as `Extensions` in src/index.ts, so drop them here.
  stripPatternProperties(schema);
  const ts = await compile(schema, typeName, {
    bannerComment: `/* Generated from schemas/${file} by scripts/generate-types.ts. Do not edit. */`,
    additionalProperties: false,
    strictIndexSignatures: true,
    style: { singleQuote: true, semi: true, printWidth: 100, trailingComma: 'all' },
  });
  writeFileSync(join(outDir, `${base}.ts`), ts);
  names.push(base);
}
writeFileSync(
  join(outDir, 'index.ts'),
  `/* Generated by scripts/generate-types.ts. Do not edit. */\n${names.map((n) => `export type * from './${n}.js';`).join('\n')}\n`,
);
console.log(`generated ${String(names.length)} type files`);
